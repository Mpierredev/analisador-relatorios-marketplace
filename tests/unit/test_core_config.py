from decimal import Decimal

from analisador.core.config import (
    ABC_CLASS_A_LIMIT,
    ABC_CLASS_B_LIMIT,
    BYTES_PER_MEGABYTE,
    CACHE_MAX_ENTRIES,
    CACHE_TTL_SECONDS,
    CENTS_PER_UNIT,
    CONFLICT_FIELD_PENALTY,
    DEFAULT_TIMEZONE,
    ENCODING_SAMPLE_BYTES,
    FALLBACK_ENCODINGS,
    GENERIC_NAME_SIMILARITY_THRESHOLD,
    HEADER_SCAN_MAX_ROWS,
    HEADER_SIMILARITY_THRESHOLD,
    HIGH_CONFIDENCE_THRESHOLD,
    IQR_LOWER_QUANTILE,
    IQR_OUTLIER_MULTIPLIER,
    IQR_UPPER_QUANTILE,
    MAX_DETECTION_SCORE,
    MAX_FILE_SIZE_BYTES,
    MAX_FILE_SIZE_MB,
    MAX_MONETARY_INTEGER_DIGITS,
    MAX_RATIO,
    MAX_ROWS,
    MEDIUM_CONFIDENCE_THRESHOLD,
    MIN_DETECTION_SCORE,
    MIN_HEADER_COLUMNS,
    MIN_OUTLIER_SAMPLE_SIZE,
    MIN_QUANTITY,
    MIN_RATIO,
    OPTIONAL_FIELD_WEIGHT,
    PREVIEW_ROW_COUNT,
    REQUIRED_FIELD_WEIGHT,
    SUPPORTED_EXTENSIONS,
    SUPPORTED_SEPARATORS,
    SYNTHETIC_ORDER_ID_PREFIX,
    TYPE_INFERENCE_SAMPLE_ROWS,
    UTF8_BOM_ENCODING,
)


def test_operational_limits_and_extensions() -> None:
    assert MAX_FILE_SIZE_MB == 25
    assert MAX_FILE_SIZE_BYTES == MAX_FILE_SIZE_MB * BYTES_PER_MEGABYTE
    assert MAX_ROWS == 200_000
    assert set(SUPPORTED_EXTENSIONS) == {".csv", ".xlsx"}
    assert list(SUPPORTED_SEPARATORS) == [",", ";", "\t"]
    assert ENCODING_SAMPLE_BYTES == 65_536
    assert HEADER_SCAN_MAX_ROWS == 30
    assert MIN_HEADER_COLUMNS == 2
    assert UTF8_BOM_ENCODING == "utf-8-sig"
    assert list(FALLBACK_ENCODINGS) == ["utf-8", "cp1252", "latin-1"]
    assert DEFAULT_TIMEZONE == "America/Sao_Paulo"
    assert CENTS_PER_UNIT == 100
    assert MAX_MONETARY_INTEGER_DIGITS == 15
    assert SYNTHETIC_ORDER_ID_PREFIX == "SYN-"
    assert MIN_QUANTITY == 1


def test_detection_weights_and_thresholds_are_consistent() -> None:
    assert MIN_RATIO == 0.0
    assert MAX_RATIO == 1.0
    assert MIN_DETECTION_SCORE == MIN_RATIO
    assert MAX_DETECTION_SCORE == MAX_RATIO
    assert REQUIRED_FIELD_WEIGHT + OPTIONAL_FIELD_WEIGHT < MAX_DETECTION_SCORE
    assert CONFLICT_FIELD_PENALTY > 0.0
    assert (
        MIN_DETECTION_SCORE
        < MEDIUM_CONFIDENCE_THRESHOLD
        < HIGH_CONFIDENCE_THRESHOLD
        < MAX_DETECTION_SCORE
    )
    assert MIN_RATIO < HEADER_SIMILARITY_THRESHOLD <= MAX_RATIO
    assert HEADER_SIMILARITY_THRESHOLD == 0.85
    assert MIN_RATIO < GENERIC_NAME_SIMILARITY_THRESHOLD <= MAX_RATIO
    assert GENERIC_NAME_SIMILARITY_THRESHOLD == 0.72
    assert TYPE_INFERENCE_SAMPLE_ROWS == 50


def test_analytics_and_ui_constants() -> None:
    assert MIN_OUTLIER_SAMPLE_SIZE == 4
    assert 0.0 < IQR_LOWER_QUANTILE < IQR_UPPER_QUANTILE < 1.0
    assert IQR_LOWER_QUANTILE == 0.25
    assert IQR_UPPER_QUANTILE == 0.75
    assert IQR_OUTLIER_MULTIPLIER == 1.5
    assert Decimal("0") < ABC_CLASS_A_LIMIT < ABC_CLASS_B_LIMIT < Decimal("1")
    assert PREVIEW_ROW_COUNT > 0
    assert CACHE_MAX_ENTRIES > 0
    assert CACHE_TTL_SECONDS > 0
